import fs from 'node:fs/promises'
import path from 'node:path'
import process from 'node:process'

const root = path.resolve(new URL('..', import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1'))
const outputFile = path.join(root, 'BOOTSTRAP_PROMPT.md')

const HEADER = `# AutopAI bootstrap prompt

AutopAI is a portable, CI-gated development orchestrator for agentic coding tools. It coordinates work through resumable phases, keeps state in local files, and owns every Git write: branches, commit validation, pushes, pull requests, CI waits, and merges.

## If the repository is available

Do not recreate the files. Follow \`README.md\` and:

1. Verify Node.js, Git, the GitHub CLI, and the target coding tool.
2. Run \`npm ci\` and \`npm link\` inside the clone.
3. Install the platform files for the target tool from \`platforms/<tool>/\`.
4. Verify \`autopai help\`.
5. In each target repository, generate \`autopai.json\` by inspecting it, then run \`autopai status --repo .\`.

Copy the core, the prompts, the runners, and the platform files from the inventory below. Do not rewrite them.

## If you are porting to another tool

The core never imports a concrete client. Read \`spec/PLATFORMS.md\` and:

1. Add \`src/runners/<tool>.js\` exporting \`runSession\`.
2. Register it in \`src/runners/index.js\`.
3. Set \`runner\` in the target repository \`autopai.json\`.
4. Recreate the agent roles and permissions under \`platforms/<tool>/\`.

The prompts, phases, state, policy, and merge logic do not change.

## Hard constraints

- Tickets, briefs, findings, and evidence are local. Never commit, push, or reference them from Git artifacts.
- No ticket paths, ADR numbers, or issue references in code, branches, commits, pull requests, or merge commits.
- Branches use \`<type>/<kebab-case-slug>\`. Commit subjects and pull request titles use \`<type>: <subject>\` with no scope parentheses.
- The executor may commit but never push, merge, rebase, force-push, or run the Git host CLI.
- The orchestrator is the only component that pushes, opens pull requests, and merges.
- Tests may be changed freely. CI build, test suite, and coverage threshold are the quality gates.
- No diagnostic reports.
- Never put secrets, tokens, or personal absolute paths in \`autopai.json\`.

## Configuration

\`autopai.json\` lives at the root of each target repository and is generated by inspecting that repository. Read \`spec/CONFIG_SCHEMA.md\` for every field. \`runner\` is required.

## Verification checklist

- \`npm test\` passes.
- \`autopai help\` works from a new shell.
- \`autopai status --repo <target>\` loads the generated configuration without errors.
- \`autopai adopt --repo <target> --branch <branch> --dry-run\` reports the plan without pushing or merging.
- \`autopai identify --repo <target> --scope branch:<branch> --dry-run\` reports the scope without running the auditor.
- \`autopai config check --repo <target>\` reports the configuration schema state without writing.
- No file outside the target repository state directory changed during a dry run.

## Source inventory

Copy every file below from the repository. Do not rewrite the contents.
`

async function main() {
  const check = process.argv.includes('--check')
  const prompt = await buildPrompt()
  if (check) {
    const existing = await fs.readFile(outputFile, 'utf8').catch(() => '')
    if (normalizeLineEndings(existing) !== normalizeLineEndings(prompt)) {
      process.stderr.write('BOOTSTRAP_PROMPT.md is out of date. Run: npm run build-bootstrap\n')
      process.exitCode = 1
      return
    }
    process.stdout.write('BOOTSTRAP_PROMPT.md is in sync.\n')
    return
  }
  await fs.writeFile(outputFile, prompt, 'utf8')
  process.stdout.write(`Wrote ${outputFile}\n`)
}

async function buildPrompt() {
  const groups = [
    ['Repository files', await sorted('AGENTS.md')],
    ['Assets', await sorted('assets')],
    ['Documentation', await sorted('docs')],
    ['Specifications', await sorted('spec')],
    ['Platform files', await sorted('platforms')],
    ['Core', await sorted('src/cli.js')],
    ['Core libraries', await sorted('src/lib')],
    ['Phases', await sorted('src/phases')],
    ['Prompts', await sorted('src/prompts')],
    ['Runners', await sorted('src/runners')],
    ['Tests', await sorted('test')]
  ]
  const sections = groups
    .filter(([, files]) => files.length > 0)
    .map(([title, files]) => `### ${title}\n\n${files.map(file => `- \`${file}\``).join('\n')}\n`)
  return `${HEADER}\n${sections.join('\n')}`
}

async function sorted(target) {
  const full = path.join(root, target)
  const stat = await fs.stat(full).catch(() => null)
  if (!stat) return []
  if (stat.isFile()) return [target]
  const entries = await fs.readdir(full, { withFileTypes: true, recursive: true })
  return entries
    .filter(entry => entry.isFile())
    .map(entry => path.relative(root, path.join(entry.parentPath ?? entry.path, entry.name)).replace(/\\/g, '/'))
    .filter(file => !file.endsWith('.map'))
    .sort()
}

function normalizeLineEndings(value) {
  return String(value).replace(/\r\n/g, '\n')
}

main().catch(error => {
  process.stderr.write(`build-bootstrap: ${error.message}\n`)
  process.exitCode = 1
})
